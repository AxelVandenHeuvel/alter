/** Small DOM helpers shared by the snapshot and query code. Pure functions of the DOM. */

const EMAIL = /[\w.+-]+@[\w-]+\.[\w.-]+/g;
const LONG_DIGITS = /\d[\d\s-]{6,}\d/g;

/** Strip obvious personal data before page text leaves the browser. */
export function redact(text: string): string {
  return text.replace(EMAIL, '[email]').replace(LONG_DIGITS, '[number]');
}

export function truncate(text: string, max: number): string {
  return text.length <= max ? text : `${text.slice(0, max - 1)}…`;
}

export function collapseWhitespace(text: string): string {
  return text.replace(/\s+/g, ' ').trim();
}

/** Visible text owned directly by the element (not by its child elements). */
export function directText(el: Element): string {
  let text = '';
  for (const node of el.childNodes) {
    if (node.nodeType === Node.TEXT_NODE) text += node.textContent ?? '';
  }
  return collapseWhitespace(text);
}

/**
 * Heuristic: class names generated by CSS-in-JS or bundlers change on every
 * deploy, so selectors built on them break. Keep only human-authored ones.
 */
export function isStableClass(name: string): boolean {
  if (name.length < 2 || name.length > 40) return false;
  if (/^(css|sc|jss|jsx|emotion|styled|svelte|astro)-/i.test(name)) return false;
  if (/^_/.test(name)) return false;
  const digits = name.match(/\d/g)?.length ?? 0;
  if (digits >= 3) return false;
  if (digits > 0 && /[a-z][A-Z]|[A-Z][a-z][A-Z]/.test(name)) return false;
  return true;
}

export function isStableId(id: string): boolean {
  return id.length > 0 && id.length <= 40 && !/^\d/.test(id) && (id.match(/\d/g)?.length ?? 0) < 4 && !/[:]/.test(id);
}

export function stableClasses(el: Element, limit = 3): string[] {
  const classes: string[] = [];
  for (const name of el.classList) {
    if (isStableClass(name)) classes.push(name);
    if (classes.length >= limit) break;
  }
  return classes;
}

export function cssEscape(value: string): string {
  return typeof CSS !== 'undefined' && CSS.escape ? CSS.escape(value) : value.replace(/[^a-zA-Z0-9_-]/g, '\\$&');
}

/** A short selector that a human (or model) can read and reuse. Not guaranteed unique. */
export function selectorHint(el: Element): string {
  const parts: string[] = [];
  let current: Element | null = el;
  while (current && parts.length < 3 && current !== current.ownerDocument.documentElement) {
    const tag = current.tagName.toLowerCase();
    if (current.id && isStableId(current.id)) {
      parts.unshift(`${tag}#${cssEscape(current.id)}`);
      break;
    }
    const classes = stableClasses(current, 2).map((c) => `.${cssEscape(c)}`).join('');
    parts.unshift(`${tag}${classes}`);
    current = current.parentElement;
  }
  return parts.join(' > ');
}

export function isHidden(el: Element): boolean {
  if (el.getAttribute('aria-hidden') === 'true') return true;
  if (typeof el.checkVisibility === 'function') {
    return !el.checkVisibility({ visibilityProperty: true, contentVisibilityAuto: false } as CheckVisibilityOptions);
  }
  const style = el.ownerDocument.defaultView?.getComputedStyle(el);
  return style?.display === 'none' || style?.visibility === 'hidden';
}

export interface Rgba {
  r: number;
  g: number;
  b: number;
  a: number;
}

let probe: CanvasRenderingContext2D | null | undefined;

/** Parse any CSS color (rgb, hex, oklch, color(), named) to sRGB by painting one pixel. */
export function parseColor(color: string): Rgba | null {
  const simple = color.match(/^rgba?\(\s*([\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)(?:[\s,/]+([\d.]+%?))?\s*\)$/);
  if (simple) {
    const alpha = simple[4] === undefined ? 1 : simple[4].endsWith('%') ? parseFloat(simple[4]) / 100 : parseFloat(simple[4]);
    return { r: Number(simple[1]), g: Number(simple[2]), b: Number(simple[3]), a: alpha };
  }
  if (probe === undefined) {
    try {
      const canvas = document.createElement('canvas');
      canvas.width = canvas.height = 1;
      probe = canvas.getContext('2d', { willReadFrequently: true });
    } catch {
      probe = null;
    }
  }
  if (!probe) return null;
  probe.clearRect(0, 0, 1, 1);
  probe.fillStyle = '#000';
  probe.fillStyle = color;
  probe.fillRect(0, 0, 1, 1);
  const [r, g, b, a] = probe.getImageData(0, 0, 1, 1).data;
  return { r: r ?? 0, g: g ?? 0, b: b ?? 0, a: (a ?? 0) / 255 };
}

/** WCAG relative luminance, 0 (black) to 1 (white). */
export function luminance({ r, g, b }: Rgba): number {
  const channel = (v: number) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
}
